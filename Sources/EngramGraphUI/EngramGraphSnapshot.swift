import Foundation

/// Immutable data for ONE explicitly selected graph. This module never opens a store.
public struct EngramGraphSnapshot: Sendable {
    public let scopeID: String
    public let graphID: UUID
    public let ownerID: UUID
    public let revisionID: String
    public let title: String
    public let memories: [EngramGraphMemory]
    public let edges: [EngramGraphEdge]
    public let coverage: EngramGraphCoverage

    public init(scopeID: String, graphID: UUID, ownerID: UUID, revisionID: String,
                title: String, memories: [EngramGraphMemory], edges: [EngramGraphEdge],
                coverage: EngramGraphCoverage) {
        self.scopeID = scopeID; self.graphID = graphID; self.ownerID = ownerID
        self.revisionID = revisionID; self.title = title
        self.memories = memories; self.edges = edges; self.coverage = coverage
    }
}

public struct EngramGraphMemory: Sendable, Identifiable {
    public let id: UUID
    public let content: String
    public let project: String
    public let topic: String
    public let importance: Int
    public let createdAt: Date
    public let lastAccessedAt: Date
    public let accessCount: Int
    public let source: String?
    /// Only an already-stored, finite embedding. No embedding is generated by this viewer.
    public let embedding: [Float]?

    public init(id: UUID, content: String, project: String, topic: String,
                importance: Int, createdAt: Date, lastAccessedAt: Date,
                accessCount: Int = 0, source: String? = nil, embedding: [Float]? = nil) {
        self.id = id; self.content = content; self.project = project; self.topic = topic
        self.importance = importance; self.createdAt = createdAt; self.lastAccessedAt = lastAccessedAt
        self.accessCount = accessCount; self.source = source; self.embedding = embedding
    }
}

public struct EngramGraphEdge: Sendable, Identifiable {
    public let id: UUID
    public let sourceID: UUID
    public let targetID: UUID
    public let relation: String
    public init(id: UUID, sourceID: UUID, targetID: UUID, relation: String) {
        self.id = id; self.sourceID = sourceID; self.targetID = targetID; self.relation = relation
    }
}

/// Counts refer to the exact selected graph, before the reader's bounded topology limits.
public struct EngramGraphCoverage: Sendable {
    public let totalMemoryCount: Int
    public let totalEdgeCount: Int
    public let omittedEmbeddingCount: Int
    public let invalidEmbeddingCount: Int
    public let isPartial: Bool
    public let statusMessage: String?
    public init(totalMemoryCount: Int, totalEdgeCount: Int,
                omittedEmbeddingCount: Int = 0, invalidEmbeddingCount: Int = 0,
                isPartial: Bool = false, statusMessage: String? = nil) {
        self.totalMemoryCount = totalMemoryCount; self.totalEdgeCount = totalEdgeCount
        self.omittedEmbeddingCount = omittedEmbeddingCount; self.invalidEmbeddingCount = invalidEmbeddingCount
        self.isPartial = isPartial; self.statusMessage = statusMessage
    }
}
