// Exact v3 fields: the upgrade fixture opens a truly absent column, not a
// current-schema row deliberately assigned NULL.
enum RestrictionV3 {
@Model @Detached
final class Memory {
    /// The memory content — a natural-language description of the knowledge to store.
    @FullText var content: String

    /// Category for organizing memories (e.g., "preferences", "architecture", "debugging", "patterns").
    var topic: String

    /// Which project this memory belongs to. Use "global" for cross-project knowledge
    /// like user preferences or general patterns. Otherwise use the project name
    /// (e.g., "Lattice", "Engram").
    var project: String

    /// Where this memory originated — provides context about how the knowledge was acquired.
    /// Examples: "conversation", "code-review", "debugging-session", or a file path.
    var source: String

    /// Vector embedding of `content` for semantic similarity search.
    /// Generated by the paraphrase-MiniLM-L6-v2 model at storage time.
    var embedding: Vector<Float>

    /// When this memory was created.
    var createdAt: Date

    /// When this memory was last accessed (recalled or updated).
    var lastAccessedAt: Date

    /// When this memory expires. Expired memories are filtered out of recall results.
    /// Defaults to `Date.distantFuture` (never expires).
    var expiresAt: Date

    /// How many times this memory has been returned by recall. Used for frequency-based ranking boost.
    var accessCount: Int

    /// Explicit importance rating (1-5). 0 means unset. Higher values boost recall ranking.
    var importance: Int

    /// Whether this memory stays on this device. Private memories are excluded
    /// from personal cloud/device sync and group sharing, even when the project's
    /// sync policy is enabled. Default: false (follow the project's personal sync policy and explicit group exposure).
    ///
    /// Retract semantics: flipping this to `true` on a memory ALREADY shared
    /// with a group emits a real DELETE to the group DB (row-level filter
    /// unmatch), removing the group's copy including teammates' edits.
    /// Author-only — enforced at the MCP handler.
    var isPrivate: Bool

    /// Who authored this memory (schema v3, Groups). Nil for legacy and
    /// never-signed-in rows. Stamped at creation from groups.json's
    /// `selfUserId`; NEVER changed by edits — attribution follows the
    /// original author, and the spoke→hub sync firewall keys on it.
    var authorUserId: UUID?

    /// Soft-delete tombstone (schema v3, Groups). Non-nil = hidden from all
    /// recall/FTS/vector reads everywhere it syncs. Used instead of hard
    /// delete whenever the memory is group-shared; recoverable by clearing
    /// (undelete). Hard purge is an admin-only server-side operation.
    var deletedAt: Date?

    /// Who tombstoned this memory (attribution for "tombstoned by X" notices).
    var deletedBy: UUID?

    /// When this memory's content/metadata was last modified (schema v3).
    /// Stamped by MemoryTools on every write. Instruments how often
    /// last-arrival-wins loses newer data today, and gives field-timestamp
    /// LWW a column to compare when it lands.
    var modifiedAt: Date?

    init(
        content: String,
        topic: String = "general",
        project: String = "global",
        source: String = "",
        embedding: Vector<Float> = Vector<Float>([]),
        createdAt: Date = Date(),
        lastAccessedAt: Date = Date(),
        expiresAt: Date = Date.distantFuture,
        accessCount: Int = 0,
        importance: Int = 0,
        isPrivate: Bool = false,
        authorUserId: UUID? = nil,
        deletedAt: Date? = nil,
        deletedBy: UUID? = nil,
        modifiedAt: Date? = nil
    ) {
        self.content = content
        self.topic = topic
        self.project = project
        self.source = source
        self.embedding = embedding
        self.createdAt = createdAt
        self.lastAccessedAt = lastAccessedAt
        self.expiresAt = expiresAt
        self.accessCount = accessCount
        self.importance = importance
        self.isPrivate = isPrivate
        self.authorUserId = authorUserId
        self.deletedAt = deletedAt
        self.deletedBy = deletedBy
        self.modifiedAt = modifiedAt
    }
}

}

@Suite("DerivationRestrictionMigration")
struct DerivationRestrictionMigrationTests {
    private func directory() throws -> URL {
        let result = try testFixtureDirectory().appendingPathComponent("restriction-schema-\(UUID())")
        try FileManager.default.createDirectory(at: result, withIntermediateDirectories: true)
        return result
    }
    private func columnPresent(_ path: URL, _ column: String) throws -> Bool {
        var db: OpaquePointer?, statement: OpaquePointer?
        #expect(sqlite3_open_v2(path.path, &db, SQLITE_OPEN_READONLY, nil) == SQLITE_OK)
        defer { sqlite3_finalize(statement); sqlite3_close(db) }
        #expect(sqlite3_prepare_v2(db, "PRAGMA table_info(Memory)", -1, &statement, nil) == SQLITE_OK)
        while sqlite3_step(statement) == SQLITE_ROW {
            if let value = sqlite3_column_text(statement, 1), String(cString: value) == column { return true }
        }
        return false
    }
    @Test func absentLegacyPolicyDoesNotBecomeDirectOnUpgrade() throws {
        let path = try directory().appendingPathComponent("legacy.sqlite")
        var old: Lattice? = try Lattice(RestrictionV3.Memory.self, configuration: .init(fileURL: path))
        try old!.add(RestrictionV3.Memory(content: "Synthetic legacy memory", project: "p"))
        #expect(try !columnPresent(path, "derivationPolicy"))
        old!.close(); old = nil
        let current = try Lattice(Memory.self, configuration: .init(fileURL: path, migration: engramMigrations))
        let row = try #require(current.objects(Memory.self).first)
        #expect(try columnPresent(path, "derivationPolicy"))
        #expect(row.derivationPolicy == nil)
        #expect(!row.isPrivate)
        #expect(row.effectiveIsPrivate)
        #expect(MemoryDerivationPolicy(rawValue: row.derivationPolicy) == nil)
        try current.add(Memory(content: "New explicit direct memory", project: "p"))
        let direct = try #require(current.objects(Memory.self).where { $0.content == "New explicit direct memory" }.first)
        #expect(direct.derivationPolicy == MemoryDerivationPolicy.direct.rawValue)
        #expect(!direct.effectiveIsPrivate)
    }
    @Test func canonicalRestrictionSurvivesCloseAndReopen() throws {
        let path = try directory().appendingPathComponent("current.sqlite")
        let a = UUID(), b = UUID()
        let policy = try #require(MemoryDerivationPolicy.derived(privateFloor: false, groupCeiling: [b.uuidString, a.uuidString]))
        var initial: Lattice? = try Lattice(Memory.self, configuration: .init(fileURL: path))
        try initial!.add(Memory(content: "Bounded synthetic memory", derivationPolicy: policy.rawValue))
        initial!.close(); initial = nil
        let reopened = try Lattice(Memory.self, configuration: .init(fileURL: path))
        let row = try #require(reopened.objects(Memory.self).first)
        #expect(MemoryDerivationPolicy(rawValue: row.derivationPolicy) == policy)
        #expect(policy.permits(group: a) && policy.permits(group: b))
        #expect(!policy.permits(group: UUID()))
        let empty = try #require(MemoryDerivationPolicy.derived(privateFloor: false, groupCeiling: []))
        #expect(!empty.permits(group: a))
        #expect(MemoryDerivationPolicy.direct.permits(group: a))
    }
    @Test func oldSchemaReopenLosesPolicyAndReupgradeFailsClosed() throws {
        let path = try directory().appendingPathComponent("old-schema-reopen.sqlite")
        let policy = try #require(MemoryDerivationPolicy.derived(privateFloor: true, groupCeiling: []))
        do {
            let current = try Lattice(Memory.self, configuration: .init(fileURL: path))
            try current.add(Memory(content: "Restricted before old-schema reopen", isPrivate: true, derivationPolicy: policy.rawValue))
            current.close()
        }
        do {
            let old = try Lattice(RestrictionV3.Memory.self, configuration: .init(fileURL: path))
            let row = try #require(old.objects(RestrictionV3.Memory.self).first)
            // Characterize old-schema behavior only: an old client does not
            // enforce the floor and is NOT qualified by this fixture.
            row.isPrivate = false
            row.content = "Edited through the old schema"
            try old.add(RestrictionV3.Memory(content: "Inserted through the old schema"))
            old.close()
        }
        let current = try Lattice(Memory.self, configuration: .init(fileURL: path))
        let edited = try #require(current.objects(Memory.self).where { $0.content == "Edited through the old schema" }.first)
        #expect(!edited.isPrivate)
        // Pinned Lattice's old-schema reopen drops the unknown column. The
        // old-client window is unsafe; current code must deny the NULL it
        // leaves, never reclassify the edited row as direct. This fixture is
        // evidence for a separate downgrade barrier, not release approval.
        #expect(edited.derivationPolicy == nil)
        #expect(edited.effectiveIsPrivate)
        let inserted = try #require(current.objects(Memory.self).where { $0.content == "Inserted through the old schema" }.first)
        #expect(inserted.derivationPolicy == nil)
        #expect(inserted.effectiveIsPrivate)
    }
    @Test func invalidOrUnknownPolicyNeverMeansDirect() {
        let a = UUID().uuidString
        let values: [String?] = [nil, "", "engram-policy:2:direct", "engram-policy:1:derived:2:",
            "engram-policy:1:derived:0:garbage", "engram-policy:1:derived:0:\(a),\(a)",
            "engram-policy:1:derived:0:\(a.lowercased())", "engram-policy:1:derived:1:\(a)",
            "engram-policy:1:direct:extra", String(repeating: "x", count: 4097)]
        for value in values { #expect(MemoryDerivationPolicy(rawValue: value) == nil) }
        #expect(MemoryDerivationPolicy.derived(privateFloor: false, groupCeiling: Set((0..<65).map { _ in UUID().uuidString })) == nil)
    }
}
